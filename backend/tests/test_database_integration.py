def test_seed_pairs_are_unique_and_every_record_is_traceable():
    from app.repositories.record_repository import DEFAULT_SEED_PATH

    data = json.loads(DEFAULT_SEED_PATH.read_text(encoding="utf-8"))
    records = data["records"]

    # Duplicate (title, source) pairs would silently skip on load and
    # break C1's uniqueness rule — the file itself must be clean.
    pairs = [
        (record["title"].strip().casefold(), record["publisher"].strip().casefold())
        for record in records
    ]
    assert len(set(pairs)) == len(pairs)

    for record in records:
        assert len(record["text"].strip()) >= 120, record["id"]
        assert record["url"].lower().startswith("https://")
        # Every record documents when its URL was checked.
        assert "URL checked 2026-10-25" in record["provenance"], record["id"]


async def test_seed_loads_completely_into_the_migrated_database(open_db):
    from app.repositories.record_repository import (
        load_seed_records,
        search_records,
        seed_records,
    )

    seed = load_seed_records()

    async with open_db() as sessions:
        async with session_scope(sessions) as session:
            added = await seed_records(session, seed)
        # Nothing was silently skipped (no hidden pair/id collisions).
        assert added == len(seed)

        async with sessions() as session:
            count = (
                await session.execute(
                    select(func.count()).select_from(HistoricalRecord)
                )
            ).scalar_one()
            assert count == len(seed)

            # Every stored record is findable through the search path.
            for record in seed[:3]:
                hits = await search_records(session, record["title"][:12])
                assert record["id"] in {hit.id for hit in hits}


