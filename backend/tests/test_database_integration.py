async def _seed_two_relationships(sessions) -> tuple[str, str, str, str, str]:
    """run + three entities + two candidate edges -> (ada, engine, babbage,
    rel_ada_engine, rel_ada_babbage) ids."""
    from app.repositories.analysis_repository import create_analysis_run
    from app.repositories.entity_repository import upsert_entities
    from app.repositories.relationship_repository import save_relationships

    async with session_scope(sessions) as session:
        await create_analysis_run(session, analysis_id="run-ev-scoped")
        entities = await upsert_entities(
            session,
            [
                {"name": "Ada Lovelace", "entity_type": "person"},
                {"name": "Analytical Engine", "entity_type": "event"},
                {"name": "Charles Babbage", "entity_type": "person"},
            ],
        )
        ada, engine, babbage = (entity.id for entity in entities)
        rel_one = await save_relationships(
            session,
            "run-ev-scoped",
            [{"source": ada, "target": engine, "label": "wrote notes for"}],
        )
        rel_two = await save_relationships(
            session,
            "run-ev-scoped",
            [{"source": ada, "target": babbage, "label": "corresponded with"}],
        )
    return ada, engine, babbage, rel_one[0].id, rel_two[0].id


async def test_evidence_is_scoped_to_its_own_relationship(open_db):
    async with open_db() as sessions:
        _, _, _, rel_one, rel_two = await _seed_two_relationships(sessions)
        await _add_support_record(sessions)

        from app.services.evidence_service import evaluate_relationship_evidence

        async with session_scope(sessions) as session:
            first = await evaluate_relationship_evidence(session, rel_one)
            second = await evaluate_relationship_evidence(session, rel_two)

        # Distinct verdicts for distinct relationships.
        assert first.status == "verified"
        assert second.status == "unsupported"

        from app.repositories.evidence_repository import list_evidence
        from app.repositories.relationship_repository import get_relationship

        async with sessions() as session:
            one_rows = await list_evidence(session, rel_one)
            two_rows = await list_evidence(session, rel_two)
            one_rel = await get_relationship(session, rel_one)
            two_rel = await get_relationship(session, rel_two)

        # Evaluating rel_two must not clobber rel_one's evidence or status.
        assert len(one_rows) == 1 and one_rel.verification_status == "verified"
        assert len(two_rows) == 1 and two_rel.verification_status == "unsupported"
        assert one_rows[0].id != two_rows[0].id
        assert one_rows[0].relationship_id == rel_one
        assert two_rows[0].relationship_id == rel_two


async def test_reevaluating_replaces_evidence_without_duplicates(open_db):
    async with open_db() as sessions:
        _, _, _, rel_one, _ = await _seed_two_relationships(sessions)
        await _add_support_record(sessions)

        from app.repositories.evidence_repository import list_evidence
        from app.services.evidence_service import evaluate_relationship_evidence

        async with session_scope(sessions) as session:
            first = await evaluate_relationship_evidence(session, rel_one)
        async with session_scope(sessions) as session:
            second = await evaluate_relationship_evidence(session, rel_one)

        assert first.status == second.status == "verified"
        async with sessions() as session:
            rows = await list_evidence(session, rel_one)
        assert len(rows) == 1  # replaced, never duplicated


