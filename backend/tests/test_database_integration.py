"""C5 — database integration tests: migrations, seed, evidence, workflow.

Complements (does not duplicate) the existing suites:

* ``test_schema.py`` (C1) — tables, columns, PKs/FKs, cascades,
  constraint violations, downgrade;
* ``test_retrieval.py`` (C2/C3) — repositories, retrieval, seed loading;
* ``test_relationships.py`` (C2/C4) — persistence, transactions,
  evidence evaluation verdicts.

This file adds C5's remaining verification:

1. **Migrations** — the frozen revision chain and Alembic's own
   drift detector (``alembic check``), which also covers CHECKs,
   indexes and defaults the manual comparison does not assert;
2. **Seed integrity** — no duplicate ``(title, source)`` pairs (they
   would silently skip on load), every record traceable to a checked
   URL, and a complete load into the migrated database;
3. **Evidence association preservation** — evidence is scoped per
   relationship and re-evaluation replaces without duplicating;
4. **Module B integration support** — the full B3 processing order end
   to end against the real seed, all-or-nothing rollback for aborted
   workflows, and sanitised failures for every relationship read.

Reproducible setup (no PostgreSQL server needed — SQLite, migrated by
the real Alembic pipeline, drives everything)::

    cd backend
    .venv/Scripts/python -m pytest tests/test_database_integration.py -q
    .venv/Scripts/python -m pytest -q -rs          # full suite
"""

