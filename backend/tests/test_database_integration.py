async def test_module_b_full_workflow_end_to_end(open_db):
    """B3's required order with the REAL modules (no API, no Module D):
    run -> entities -> attach -> retrieval -> candidate -> evidence
    evaluation -> completed metadata, then B4-style read-backs."""
    from app.repositories.analysis_repository import (
        attach_entities,
        create_analysis_run,
        get_analysis_run,
        update_analysis_run,
    )
    from app.repositories.entity_repository import upsert_entities
    from app.repositories.evidence_repository import list_evidence
    from app.repositories.record_repository import load_seed_records, seed_records
    from app.repositories.relationship_repository import (
        get_relationship,
        list_relationships,
        save_relationships,
    )
    from app.services.evidence_service import evaluate_relationship_evidence
    from app.services.retrieval_service import search_historical_records

    async with open_db() as sessions:
        # -- the whole workflow is one transaction (all-or-nothing) --------
        async with session_scope(sessions) as session:
            # Module C's curated store is part of the environment.
            assert await seed_records(session, load_seed_records()) > 0

            # 1. accepted upload -> run row
            await create_analysis_run(
                session,
                analysis_id="run-wf",
                original_filename="plaque.jpg",
                content_type="image/jpeg",
            )

            # 2-3. extraction output -> canonical entities + links
            entities = await upsert_entities(
                session,
                [
                    {"name": "Ada Lovelace", "entity_type": "person"},
                    {"name": "Analytical Engine", "entity_type": "event"},
                ],
            )
            await attach_entities(
                session,
                "run-wf",
                [{"entity_id": entity.id, "confidence": 0.9} for entity in entities],
            )

            # 4. Module C retrieval
            hits = await search_historical_records(session, "Ada Lovelace", limit=5)
            assert hits and hits[0].record.id == "rec-ada-lovelace"

            # 5. Module D candidate persisted as an *unverified* proposal
            (relationship,) = await save_relationships(
                session,
                "run-wf",
                [
                    {
                        "source": entities[0].id,
                        "target": entities[1].id,
                        "label": "wrote notes for",
                        "verificationStatus": "unverified",
                    }
                ],
            )

            # 6. evidence evaluation over the real seed
            evaluation = await evaluate_relationship_evidence(session, relationship.id)
            assert evaluation.status == "verified"  # from records, not from the model
            assert evaluation.records_considered >= 1

            # 7. persist final analysis metadata
            await update_analysis_run(
                session,
                "run-wf",
                status="completed",
                progress=1.0,
                extracted_text="Ada Lovelace and the Analytical Engine",
                warnings=["OCR confidence low"],
            )

        # -- read-backs exactly as B4's endpoints would do ------------------
        async with sessions() as session:
            run = await get_analysis_run(session, "run-wf")
            assert run.status == "completed" and run.progress == 1.0
            assert run.extracted_text and run.warnings == ["OCR confidence low"]

            relationships = await list_relationships(session, "run-wf")
            assert len(relationships) == 1
            stored = await get_relationship(session, relationships[0].id)
            assert stored.verification_status == "verified"
            assert stored.summary and "Supported" in stored.summary

            evidence = await list_evidence(session, stored.id)
            assert evidence and evidence[0].source.strip()  # traceable publisher
            assert "Ada Lovelace" in (evidence[0].excerpt or "")

            links = (
                await session.execute(
                    select(AnalysisEntity).where(AnalysisEntity.analysis_id == "run-wf")
                )
            ).scalars().all()
            assert len(links) == 2

            # The record store is still searchable after the workflow.
            again = await search_historical_records(session, "Ada Lovelace")
            assert again and again[0].record.id == "rec-ada-lovelace"


async def test_aborted_workflow_leaves_no_partial_rows(open_db):
    """B3's rollback contract: a failed workflow never leaves half-written
    state (run row, entity links or seeded records)."""
    from app.repositories.analysis_repository import (
        create_analysis_run,
        get_analysis_run,
    )
    from app.repositories.entity_repository import (
        find_entities_by_normalized_names,
        upsert_entities,
    )
    from app.repositories.record_repository import (
        load_seed_records,
        search_records,
        seed_records,
    )

    async with open_db() as sessions:
        with pytest.raises(RuntimeError, match="pipeline failed"):
            async with session_scope(sessions) as session:
                await create_analysis_run(session, analysis_id="run-abort")
                await upsert_entities(
                    session, [{"name": "Ada Lovelace", "entity_type": "person"}]
                )
                await seed_records(session, load_seed_records()[:2])
                raise RuntimeError("pipeline failed")

        async with sessions() as session:
            assert await get_analysis_run(session, "run-abort") is None
            assert await find_entities_by_normalized_names(
                session, ["ada lovelace"]
            ) == []
            assert await search_records(session, "Babbage") == []


async def test_relationship_reads_fail_safely_when_database_unavailable(tmp_path):
    """Every C5-touched relationship read translates a broken database into
    DatabaseUnavailableError — never raw driver/SQL text."""
    from app.db.session import create_engine, create_session_factory
    from app.repositories.relationship_repository import (
        get_relationship,
        list_relationships,
        set_relationship_verification,
    )

    engine = create_engine(f"sqlite+aiosqlite:///{tmp_path}/no-such-dir/x.db")
    sessions = create_session_factory(engine)
    try:
        async with sessions() as session:
            with pytest.raises(DatabaseUnavailableError) as excinfo:
                await list_relationships(session, "run-x")
        async with sessions() as session:
            with pytest.raises(DatabaseUnavailableError) as excinfo:
                await get_relationship(session, "rel-x")
        async with sessions() as session:
            with pytest.raises(DatabaseUnavailableError) as excinfo:
                await set_relationship_verification(
                    session, "rel-x", verification_status="verified"
                )
    finally:
        await engine.dispose()

    message = str(excinfo.value)  # last failure; all share the wording
    assert "unavailable" in message.casefold()
    for leak in ("sqlite", "SELECT", "OperationalError", str(tmp_path)):
        assert leak not in message
